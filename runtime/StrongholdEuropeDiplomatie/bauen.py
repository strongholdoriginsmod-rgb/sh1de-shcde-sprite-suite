"""Baut die Diplomatie als eigenstaendiges BepInEx-Plugin.

Warum es dieses Skript gibt
---------------------------
Die Diplomatie war in die Europa-Laufzeit einkompiliert. Ein Neubau des
Europa-Pakets mit ``"diplomacy": false`` hat sie am 05.09.2026 stumm wieder
abgeschaltet, obwohl an der Diplomatie nichts geaendert worden war. Solange
Code und Grafikpaket dasselbe Erzeugnis sind, kann das jederzeit erneut
passieren. Als eigenes Plugin haengt die Diplomatie an ihrem eigenen Ordner.

Was hier erzeugt wird
---------------------
* ``GeneratedDiplomatieContract.g.cs`` — die festgeschriebenen V1-Werte und die
  Voraussetzungstabelle, die ``RuntimeBuildGuard`` erwartet. Die Werte kommen
  aus ``profiles/diplomacy-v1-canary.json`` und werden gegen
  ``runtime_build._DIPLOMACY_RULES_V1`` gegengerechnet: zwei Quellen, ein
  Vergleich, kein abgeschriebener Wert.
* ``StrongholdEuropeDiplomatie.dll`` — uebersetzt aus dem *verlinkten*
  Quelltext von ``runtime/StrongholdEuropeDE.Runtime``. Keine Kopie.
* Das Plugin-Verzeichnis mit ``info.json`` und dem HUD-Patch.

Aufruf::

    python runtime/StrongholdEuropeDiplomatie/bauen.py
    python runtime/StrongholdEuropeDiplomatie/bauen.py --install "D:/Games/..."
"""

