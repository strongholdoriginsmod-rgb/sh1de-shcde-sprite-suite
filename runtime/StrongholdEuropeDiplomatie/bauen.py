def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _pinned_rules() -> dict[str, int]:
    """Die V1-Werte aus dem Profil, gegen den Erzeuger gegengerechnet."""

    profile = json.loads(DIPLOMACY_PROFILE.read_text(encoding="utf-8"))
    if profile.get("id") != "diplomacy-v1-canary":
        raise BauFehler("Diplomatie-Quellprofil hat seine Identitaet gewechselt")
    rules = profile.get("diplomacy_rules")
    if not isinstance(rules, dict):
        raise BauFehler("Diplomatie-Quellprofil fuehrt keine Regeln")
    if set(rules) != set(_DIPLOMACY_RULES_KEYS):
        fehlend = sorted(set(_DIPLOMACY_RULES_KEYS) - set(rules))
        zuviel = sorted(set(rules) - set(_DIPLOMACY_RULES_KEYS))
        raise BauFehler(
            f"Regelsatz weicht vom Vertrag ab: fehlend={fehlend} zusaetzlich={zuviel}"
        )
    for key, value in sorted(rules.items()):
        if not isinstance(value, int) or isinstance(value, bool):
            raise BauFehler(f"diplomacy_rules.{key} ist keine ganze Zahl")
        if value != _DIPLOMACY_RULES_V1[key]:
            raise BauFehler(
                f"diplomacy_rules.{key}={value} weicht vom festgeschriebenen "
                f"V1-Wert {_DIPLOMACY_RULES_V1[key]} ab"
            )
    return dict(rules)


def _pascal(key: str) -> str:
    return "".join(part.capitalize() for part in key.split("_"))


