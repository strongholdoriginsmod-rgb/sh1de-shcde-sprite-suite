"""Origins campaign and seasonal asset authoring UI (draft only, no game hooks).

Actual MenuFeature, LegacyCampaignScreen and SeasonDirector require compatible
C# runtime integration, which cannot be generated by an asset-only editor.
"""
from __future__ import annotations

from pathlib import Path
import json
import tkinter as tk
from tkinter import ttk,filedialog,messagebox,simpledialog

from origins_runtime_authoring import (
    GM_IDS,validate_campaign,write_campaign_draft,write_season_draft,
    WorkshopError,
)
from origins_runtime_offline_qa import (
    run_offline_qa,verify_campaign,verify_season,
)


class OriginsRuntimeWorkshop(tk.Toplevel):
    def __init__(self,parent,*,project:Path):
        self.project=Path(project)
        super().__init__(parent)
        self.title("Origins · Kampagnen und Jahreszeiten manuell entwerfen")
        self.geometry("1050x750")
        self.minsize(720,550)
        self.name=tk.StringVar(self,value="meine-kampagne")
        self.title_var=tk.StringVar(self,value="Meine Kampagne")
        self.number=tk.StringVar(self,value="1")
        self.mission_title=tk.StringVar(self,value="Erste Mission")
        self.mapname=tk.StringVar(self,value="Antioch.map")
        self.act=tk.StringVar(self,value="Akt 1")
        self.pack_id=tk.StringVar(self,value="mein-winterpaket")
        self.group=tk.StringVar(self,value="tree_pine")
        self.atlas_path=tk.StringVar(self)
        self.season_maps=tk.StringVar(self,value="Antioch.map")
        self.status=tk.StringVar(self,value="Nur eigene QA-Drafts; keine Spielinstallation")
        self.missions={}
        self.season_groups={}
        self.saved_campaign_slug=None
        self.saved_season_pack=None
        notebook=ttk.Notebook(self)
        notebook.pack(fill="both",expand=True,padx=10,pady=7)
        campaign=ttk.Frame(notebook,padding=10)
        season=ttk.Frame(notebook,padding=10)
        notebook.add(campaign,text="Kampagnen / Missionsseiten")
        notebook.add(season,text="Saison-Atlanten / Gruppen")
        self._campaign_ui(campaign)
        self._season_ui(season)
        ttk.Label(self,textvariable=self.status,wraplength=1000,
                  foreground="#707c8f").pack(fill="x",padx=14,pady=7)

    def _campaign_ui(self,parent):
        heading=ttk.Frame(parent);heading.pack(fill="x")
        ttk.Label(heading,text="Kampagnen-Spezifikation",font=("Segoe UI",14,"bold")
                  ).pack(side="left")
        ttk.Label(parent,text="Die historische Origins-Laufzeit verwendet 21 Missionen, "
                  "Missionsfortschritt und die Befehle LegacyM1–LegacyM21/LegacyStart. "
                  "Dieses Werkzeug erstellt dafür vollständig editierbare Daten und "
                  "einen XAML-Entwurf. Ohne getesteten C#-Handler ist er nicht installierbar.",
                  wraplength=920).pack(fill="x",pady=8)
        meta=ttk.Frame(parent);meta.pack(fill="x",pady=4)
        ttk.Label(meta,text="Interne Kampagnen-ID").pack(side="left")
        ttk.Entry(meta,textvariable=self.name,width=25).pack(side="left",padx=7)
        ttk.Label(meta,text="Menütitel").pack(side="left")
        ttk.Entry(meta,textvariable=self.title_var,width=33).pack(side="left",padx=7)
        self.mission_list=ttk.Treeview(parent,columns=("map","act"),show="tree headings",
                                      height=12)
        self.mission_list.heading("#0",text="Missionsnummer und Titel")
        self.mission_list.heading("map",text="Karte")
        self.mission_list.heading("act",text="Akt")
        self.mission_list.column("#0",width=430)
        self.mission_list.column("map",width=240)
        self.mission_list.column("act",width=160)
        self.mission_list.pack(fill="both",expand=True,pady=8)
        self.mission_list.bind("<<TreeviewSelect>>",self._select_mission)
        form=ttk.Frame(parent);form.pack(fill="x",pady=6)
        for label,var,width in (
            ("Nr.",self.number,5),
            ("Missionsname",self.mission_title,26),
            ("Karten-Datei",self.mapname,21),
            ("Akt",self.act,15),
        ):
            ttk.Label(form,text=label).pack(side="left")
            ttk.Entry(form,textvariable=var,width=width).pack(side="left",padx=(3,8))
        row=ttk.Frame(parent);row.pack(fill="x",pady=5)
        ttk.Button(row,text="Mission anlegen / ändern",
                   command=self.add_mission).pack(side="left")
        ttk.Button(row,text="Ausgewählte Mission entfernen",
                   command=self.delete_mission).pack(side="left",padx=8)
        ttk.Button(row,text="Vorhandene Kampagne laden",
                   command=self.load_campaign).pack(side="left",padx=8)
        ttk.Button(row,text="C#-Kern offline kompilieren & testen",
                   command=self.compile_campaign).pack(side="right",padx=7)
        ttk.Button(row,text="Geprüften QA-Kampagnenentwurf speichern",
                   command=self.save_campaign).pack(side="right")

    def _select_mission(self,event=None):
        selection=self.mission_list.selection()
        if not selection:return
        index=int(selection[0])
        info=self.missions.get(index)
        if info is None:return
        self.number.set(str(index))
        self.mission_title.set(info["title"])
        self.mapname.set(info["map"])
        self.act.set(info["act"])

    def _render_missions(self):
        self.mission_list.delete(*self.mission_list.get_children())
        for index,info in sorted(self.missions.items()):
            self.mission_list.insert("", "end", iid=str(index),
                  text=f"{index:02d} · {info['title']}",
                  values=(info["map"],info["act"]))

    def add_mission(self):
        try:
            index=int(self.number.get())
            if not 1<=index<=21:raise WorkshopError("Missionsnummer muss 1–21 sein")
            row={"number":index,"title":self.mission_title.get(),
                 "map":self.mapname.get(),"act":self.act.get()}
            planned=dict(self.missions)
            planned[index]=row
            validate_campaign({
                "name":self.name.get(),"title":self.title_var.get(),
                "missions":list(planned.values()),
            })
            self.missions=planned
            self._render_missions()
            self.status.set(f"Mission {index} aktualisiert · nicht gespeichert")
        except (ValueError,TypeError) as exc:
            messagebox.showerror("Ungültige Mission",str(exc),parent=self)

    def delete_mission(self):
        item=self.mission_list.selection()
        if item:self.missions.pop(int(item[0]),None)
        self._render_missions()

    def load_campaign(self):
        slug=simpledialog.askstring(
            "Kampagnenentwurf öffnen",
            "Vorhandene private Kampagnen-ID:",
            initialvalue=self.name.get(),parent=self)
        if not slug:return
        try:
            from hud_menu_workspace import workspace
            plan,_verified_code=verify_campaign(workspace(self.project),slug)
            self.name.set(plan["name"])
            self.title_var.set(plan["title"])
            self.missions={row["number"]:row for row in plan["missions"]}
            self._render_missions()
            self.saved_campaign_slug=slug
            self.status.set(f"Kampagne {slug} mit SHA-Nachweis geladen. "
                            "Änderungen nur unter neuer Kampagnen-ID speichern.")
        except (OSError,ValueError) as exc:
            messagebox.showerror("Kampagne nicht geladen",str(exc),parent=self)

    def save_campaign(self):
        try:
            plan={
                "name":self.name.get(),
                "title":self.title_var.get(),
                "missions":list(self.missions.values()),
            }
            validate_campaign(plan)
            if not messagebox.askyesno("Nur Runtime-Entwurf",
                    "Kampagnen-Dateien und XAML-Entwurf speichern?\n"
                    "Ohne separat getesteten Origins-C#-Handler sind LegacyM1–21 "
                    "und LegacyStart keine funktionierenden Spielaktionen.",
                    parent=self,default="no"):
                return
            saved=write_campaign_draft(self.project,plan)
            self.saved_campaign_slug=plan["name"]
            self.status.set("Privater Kampagnenentwurf: "+saved["output"])
        except (OSError,ValueError) as exc:
            messagebox.showerror("Kampagne",str(exc),parent=self)

    def check_runtime(self):
        """Cross-check authored campaign and optional saved season together."""
        try:
            slug=self.saved_campaign_slug or self.name.get()
            report=run_offline_qa(self.project,slug,self.saved_season_pack)
            self.status.set("C#-Gesamtabnahme bestanden (nur offline): "+
                            report["output"]+
                            " · native Engine weiterhin gesperrt")
        except (OSError,ValueError) as exc:
            messagebox.showerror("Origins C# Gesamtabnahme",str(exc),parent=self)

    def compile_campaign(self):
        try:
            from origins_runtime_compiler import compile_offline
            if not messagebox.askyesno(
                "C#-Kern offline prüfen",
                "Die von dir entworfenen Kampagnendaten mit dem separaten "
                "Windows-.NET-Compiler prüfen?\n"
                "Es entsteht KEIN Spielplugin und keine BepInEx-Installation.",
                parent=self,default="no"):
                return
            target=self.project.parent/".origins-runtime-candidates"/self.name.get()
            proof=compile_offline(project=self.project,candidate=target,kind="campaign")
            self.status.set("Kampagnen-C#-Kern offline getestet: "+
                            proof["compiled_dll_sha256"][:16]+
                            " · noch keine native Ingame-Anbindung.")
        except (OSError,ValueError) as exc:
            messagebox.showerror("C#-Kompilierung",str(exc),parent=self)

    def _season_ui(self,parent):
        ttk.Label(parent,text="Kartenabhängige Origins-Saisonpakete",
                  font=("Segoe UI",14,"bold")).pack(anchor="w")
        ttk.Label(parent,text="Eigene PNG-Gruppenatlanten importieren; GM-IDs "
                  "werden mit den sechs historisch nachgewiesenen Gruppen "
                  "verglichen. Die Laufzeitumschaltung bei MapLoad/Save/Unload "
                  "erfordert danach einen getesteten Origins-SeasonDirector.",
                  wraplength=920).pack(fill="x",pady=8)
        row=ttk.Frame(parent);row.pack(fill="x")
        ttk.Label(row,text="Pack-ID").pack(side="left")
        ttk.Entry(row,textvariable=self.pack_id,width=31).pack(side="left",padx=8)
        frame=ttk.Frame(parent);frame.pack(fill="x",pady=8)
        ttk.Label(frame,text="GM-Gruppe").pack(side="left")
        ttk.Combobox(frame,values=list(GM_IDS),textvariable=self.group,
                     state="readonly",width=23).pack(side="left",padx=7)
        ttk.Label(frame,text="Atlas-Verzeichnis").pack(side="left")
        ttk.Entry(frame,textvariable=self.atlas_path).pack(side="left",fill="x",
                                                               expand=True,padx=6)
        ttk.Button(frame,text="Wählen",command=self.choose_atlas).pack(side="left")
        row=ttk.Frame(parent);row.pack(fill="x",pady=6)
        ttk.Button(row,text="Atlas zur Saison hinzufügen",
                   command=self.add_season).pack(side="left")
        ttk.Button(row,text="Vorhandenen Saisonentwurf laden",
                   command=self.load_season).pack(side="left",padx=8)
        self.groups=ttk.Treeview(parent,columns=("gm","directory"),
                                 show="headings",height=13)
        self.groups.heading("gm",text="Verifizierte GM-Gruppe")
        self.groups.heading("directory",text="Atlas-Quelle (nur lesen)")
        self.groups.column("gm",width=150,stretch=False)
        self.groups.column("directory",width=560)
        self.groups.pack(fill="both",expand=True,pady=8)
        route=ttk.Frame(parent);route.pack(fill="x",pady=6)
        ttk.Label(route,text="Für Karten (durch Semikolon getrennte .map-Namen):").pack(side="left")
        ttk.Entry(route,textvariable=self.season_maps).pack(
            side="left",fill="x",expand=True,padx=6)
        buttons=ttk.Frame(parent);buttons.pack(fill="x",pady=7)
        ttk.Button(buttons,text="C#-Saisonlogik offline kompilieren & testen",
                   command=self.compile_season).pack(side="right",padx=5)
        ttk.Button(buttons,text="Kampagne + Saison zusammen prüfen",
                   command=self.check_runtime).pack(side="left",padx=5)
        ttk.Button(buttons,text="Saison-Atlas-Entwurf erstellen (kein Spielinstall)",
                   command=self.save_season).pack(side="right")

    def choose_atlas(self):
        value=filedialog.askdirectory(parent=self,title="Privaten Gruppenatlas wählen")
        if value:self.atlas_path.set(value)

    def add_season(self):
        try:
            name=self.group.get()
            if name not in GM_IDS:raise WorkshopError("Unknown GM group")
            folder=Path(self.atlas_path.get())
            if not folder.is_dir():raise WorkshopError("Choose an atlas directory")
            # All checks are repeated by the backend at publication time.
            self.season_groups[name]=folder
            self.groups.delete(*self.groups.get_children())
            for key,path in sorted(self.season_groups.items()):
                self.groups.insert("","end",values=(key,str(path)))
            self.status.set(f"{len(self.season_groups)} Saison-Gruppen vorgemerkt")
        except (OSError,ValueError) as exc:
            messagebox.showerror("Saison",str(exc),parent=self)

    def load_season(self):
        chosen=simpledialog.askstring(
            "Saisonentwurf öffnen","Vorhandene private Saison-Pack-ID:",
            initialvalue=self.pack_id.get(),parent=self)
        if not chosen:return
        try:
            from hud_menu_workspace import workspace
            project=workspace(self.project)
            maps,_code=verify_season(project,chosen)
            folder=project.parent/".origins-runtime-candidates"/("season-"+chosen)
            status=json.loads((folder/"qa-status.json").read_text("utf8"))
            self.pack_id.set(chosen)
            self.season_maps.set("; ".join(maps))
            self.season_groups={
                row["gm"]:folder/row["gm"] for row in status["group_hashes"]
            }
            self.groups.delete(*self.groups.get_children())
            for name,folder_path in sorted(self.season_groups.items()):
                self.groups.insert("","end",values=(name,str(folder_path)))
            self.saved_season_pack=chosen
            self.status.set(f"Saison {chosen} mit Original-Atlas-Hashes geladen. "
                            "Neue ID zum Veröffentlichen weiterer Entwürfe wählen.")
        except (OSError,ValueError) as exc:
            messagebox.showerror("Saison nicht geladen",str(exc),parent=self)

    def compile_season(self):
        try:
            from origins_runtime_compiler import compile_offline
            if not messagebox.askyesno(
                "Saisonlogik offline prüfen",
                "Die authored Karten-/Saisonrouten als C#-Kern kompilieren und "
                "testen?\nEs erfolgt KEINE Installation im Spiel.",
                parent=self,default="no"):
                return
            target=(self.project.parent/".origins-runtime-candidates"/
                    ("season-"+self.pack_id.get()))
            proof=compile_offline(project=self.project,candidate=target,kind="season")
            self.status.set("Saison-C#-Routen offline getestet: "+
                            proof["compiled_dll_sha256"][:16]+
                            " · Script-Extender-Anbindung fehlt.")
        except (OSError,ValueError) as exc:
            messagebox.showerror("Saisonkompilierung",str(exc),parent=self)

    def save_season(self):
        try:
            if not messagebox.askyesno(
                "Nur Saison-Entwurf", "Quellatlanten prüfen und eine "
                "private QA-Kopie mit pack.json erzeugen?\n"
                "Es erfolgt KEINE Script-Extender- oder Spielinstallation.",
                parent=self,default="no"):
                return
            map_names=[part.strip() for part in self.season_maps.get().split(";")]
            result=write_season_draft(self.project,
                        pack_id=self.pack_id.get(),groups=self.season_groups,
                        map_routes=map_names)
            self.saved_season_pack=self.pack_id.get()
            self.status.set("Private Saison-QA-Kopie: "+result["output"])
        except (OSError,ValueError) as exc:
            messagebox.showerror("Saison",str(exc),parent=self)
