from __future__ import annotations

from dataclasses import dataclass
import re


@dataclass(frozen=True)
class LoaderGroup:
    """One ``spriteLoader.addGMFile`` registration in the pinned Crusader build."""

    gm_enum: str
    dash_format: bool
    plain_shader: bool
    declared_image_count: int
    custom_palette: bool
    id_offset: int
    additional_storage: int

    @property
    def owns_its_gm_arrays(self) -> bool:
        """True when this group alone defines the size and indexing of its arrays.

        ``addGMFile`` allocates ``gmSprites[id]`` with
        ``highest index + 1 + additionalStorage`` slots, but only when
        ``additionalStorage >= 0``, and writes each frame at ``index + ID_Offset``.

        SHCDE-SE 1.39 knows neither mechanism: ``GameAtlasManagerAPI.ApplySingle``
        sizes the new array as ``highest index in the override JSON + 1``, copies
        ``min(old length, new length)`` vanilla entries, and writes at the raw
        parsed index. So a group is safe to override only when both knobs are
        zero:

        * ``ID_Offset != 0`` — the group is a tenant writing at a shifted index,
          so an override would place its art over the host group's own frames.
        * ``additionalStorage != 0`` — the vanilla array is deliberately wider
          than this group's own frames. A negative value means the group does not
          allocate at all; a positive value means it reserves room for a tenant.
          Either way an override shrinks the array and destroys the reserved
          slots.
        """

        return self.id_offset == 0 and self.additional_storage == 0


