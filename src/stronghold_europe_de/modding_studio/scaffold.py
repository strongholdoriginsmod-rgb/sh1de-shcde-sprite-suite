"""Generate non-deployed C# APIShared consumer source with explicit ABI gates."""
from __future__ import annotations

from .catalog import API_RELEASE, MIN_SCRIPT_EXTENDER
from .safety import json_bytes
from .model import validate_project


def _csharp_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def plugin_scaffold(project: dict) -> dict[str, bytes]:
    project = validate_project(project)
    ident = project["project_id"]
    guid = "spritesuite.studio." + ident
    title = project["title"]
    # The generated source is inert apart from diagnostic initialization:
    # the mod author must explicitly implement and test a consumer before
    # a real game build/deployment. No BepInEx/SE/APIShared DLLs are shipped.
    source = (
        "// Generated by SpriteSuite 3; diagnostic-only, not approved for game installation.\n"
        "// Implements no gameplay changes and registers no native detours.\n"
        "using System;\n"
        "using System.Threading;\n"
        "using APIShared;\n"
        "using BepInEx;\n\n"
        "namespace SpriteSuiteAuthoring\n{\n"
        "    [BepInPlugin(Guid, " + _csharp_string(title) + ', "0.1.0")]\n'
        "    [BepInDependency(" + _csharp_string("000shcdese") + ", "
        + _csharp_string(MIN_SCRIPT_EXTENDER) + ")]\n"
        "    [BepInDependency(" + _csharp_string("APIShared_Serp") + ", "
        + _csharp_string(API_RELEASE) + ")]\n"
        "    public sealed class StudioPlugin : BaseUnityPlugin\n    {\n"
        "        public const string Guid = " + _csharp_string(guid) + ";\n"
        "        private static readonly ModApiClient Api = ApiShared.ForMod(Guid);\n"
        "        private SynchronizationContext unityContext;\n\n"
        "        private void Awake()\n        {\n"
        "            unityContext = SynchronizationContext.Current;\n"
        "            if (unityContext == null)\n            {\n"
        "                Logger.LogError(\"No Unity synchronization context; remain inactive.\");\n"
        "                return;\n            }\n"
        "            Logger.LogInfo(\"SpriteSuite Studio source-only adapter loaded; no actions active.\");\n"
        "            Api.WhenReady(OnReady);\n        }\n\n"
        "        private void OnReady(ModApiClient client)\n        {\n"
        "            // WhenReady is not a Unity-thread dispatcher. Do not call Noesis here.\n"
        "            var target = unityContext;\n"
        "            if (target == null) return;\n"
        "            target.Post(_ =>\n            {\n"
        "                if (this != null)\n"
        "                    Logger.LogInfo(\"APIShared readiness callback completed; no hooks registered.\");\n"
        "            }, null);\n        }\n    }\n}\n"
    )
    project_file = r"""<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net481</TargetFramework>
    <LangVersion>12.0</LangVersion>
    <Nullable>disable</Nullable>
    <AssemblyName>SpriteSuiteAuthoringPlugin</AssemblyName>
    <Deterministic>true</Deterministic>
    <CopyLocalLockFileAssemblies>false</CopyLocalLockFileAssemblies>
  </PropertyGroup>
  <ItemGroup>
    <Reference Include="BepInEx">
      <HintPath>$(GameDir)\BepInEx\core\BepInEx.dll</HintPath><Private>false</Private>
    </Reference>
    <Reference Include="SHCDESE">
      <HintPath>$(GameDir)\BepInEx\plugins\000shcdese\SHCDESE.dll</HintPath><Private>false</Private>
    </Reference>
    <Reference Include="APIShared">
      <HintPath>$(GameDir)\BepInEx\plugins\APIShared_Serp\APIShared.dll</HintPath><Private>false</Private>
    </Reference>
    <Reference Include="APIShared.Content">
      <HintPath>$(GameDir)\BepInEx\plugins\APIShared_Serp\APIShared.Content.dll</HintPath><Private>false</Private>
    </Reference>
    <Reference Include="UnityEngine">
      <HintPath>$(GameDir)\Stronghold Crusader Definitive Edition_Data\Managed\UnityEngine.dll</HintPath><Private>false</Private>
    </Reference>
    <Reference Include="UnityEngine.CoreModule">
      <HintPath>$(GameDir)\Stronghold Crusader Definitive Edition_Data\Managed\UnityEngine.CoreModule.dll</HintPath><Private>false</Private>
    </Reference>
  </ItemGroup>
  <Target Name="ValidateExternalReferences" BeforeTargets="ResolveReferences">
    <Error Condition="'$(GameDir)' == ''" Text="GameDir is required for an audited manual build." />
    <Error Condition="!Exists('$(GameDir)\BepInEx\plugins\APIShared_Serp\APIShared.dll')" Text="APIShared.dll must exist; exact version/hash requires separate verification." />
    <Error Condition="!Exists('$(GameDir)\BepInEx\plugins\APIShared_Serp\APIShared.Content.dll')" Text="The matching APIShared.Content.dll must exist." />
    <Error Condition="!Exists('$(GameDir)\BepInEx\plugins\000shcdese\SHCDESE.dll')" Text="Script Extender is missing." />
    <Error Condition="!Exists('$(GameDir)\BepInEx\core\BepInEx.dll')" Text="BepInEx runtime is missing." />
    <Error Condition="!Exists('$(GameDir)\Stronghold Crusader Definitive Edition_Data\Managed\UnityEngine.CoreModule.dll')" Text="UnityEngine.CoreModule.dll is missing." />
  </Target>
</Project>
"""
    info = {
        "GUID": guid,
        "Author": "SpriteSuite user",
        "Name": title,
        "Description": "Source-only diagnostic scaffold; not an in-game compatibility approval",
        "Version": "0.1.0",
        "Manifest": 1,
        "NetworkMode": 1,
        "MinimumScriptExtenderVersion": MIN_SCRIPT_EXTENDER,
        "Dependencies": [{"GUID": "APIShared_Serp", "MinimumVersion": API_RELEASE}],
    }
    readme = (
        "# Diagnostic-only APIShared consumer scaffold\n\n"
        "The generated Plugin.cs is **source**, not a validated game mod.\n"
        "It registers no gameplay, Noesis or native hooks. To develop features,\n"
        "use the public APIShared contracts from the exact release and verify\n"
        "the runtime assemblies and game DLL hash before compiling for SHCDE.\n\n"
        "Use `dotnet build -c Release -p:GameDir=<verified-game-root>` only after\n"
        "reviewing dependencies. Do not bundle BepInEx, Script Extender,\n"
        "APIShared, Harmony or game DLLs in a consumer release.\n"
        "A compiled assembly is **not** an in-game QA pass.\n"
    )
    return {
        "plugin/Plugin.cs": source.encode("utf-8"),
        "plugin/SpriteSuiteAuthoringPlugin.csproj": project_file.encode("utf-8"),
        "plugin/info.json": json_bytes(info),
        "plugin/README.md": readme.encode("utf-8"),
    }
